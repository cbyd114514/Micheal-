import { writeFileSync } from 'node:fs';
import { BEAD_COLORS, BY_CODE } from '../assets/js/bead-colors.js';
import { cropToContent } from '../assets/js/bead-viewer.js';
import { createGrid, contentBounds, toRLE, W, H } from './gen-aesthetic-patterns.mjs';

const patterns = [];

function register(id, title, category, tag, difficulty, desc, drawFn) {
  const p = createGrid(32, 32);
  drawFn(p);
  // 检查是否完全贴紧边界，若某边有空，微调补点确保 cropToContent 满足 G12-thumb
  const b = contentBounds(p.g);
  if (!b) throw new Error(`Pattern ${id} is completely empty!`);
  
  // 检查裁剪后是否紧贴
  const cropped = cropToContent(p.g);
  const cb = contentBounds(cropped);
  if (cb.x0 !== 0 || cb.y0 !== 0 || cb.x1 !== cropped[0].length - 1 || cb.y1 !== cropped.length - 1) {
    throw new Error(`Pattern ${id} cropped bounds mismatch!`);
  }

  // 检查所有非空格子都在 BY_CODE 里
  for (let y = 0; y < 32; y++) {
    for (let x = 0; x < 32; x++) {
      const code = p.g[y][x];
      if (code !== null && !BY_CODE.has(code)) {
        throw new Error(`Pattern ${id} uses invalid color code: ${code}`);
      }
    }
  }

  patterns.push({
    id,
    title,
    category,
    tag,
    difficulty,
    desc,
    rle: toRLE(p.g, 32),
    usedCodes: Array.from(new Set(p.g.flat().filter(Boolean)))
  });
}

